# ==========================================
# SIMBA INSIGHTS — CUSTOMER SEGMENTATION PIPELINE
# ==========================================

import pandas as pd
import numpy as np

# ---------- 1. EXTRACT ----------
df = pd.read_csv('marketing_data.csv', encoding='utf-8-sig')

# ---------- 2. CLEAN ----------
df.columns = df.columns.str.strip()
df = df.loc[:, ~df.columns.str.contains('^Unnamed')]

raw_rows = len(df)
df = df.drop_duplicates(subset='ID', keep='first')
df = df.drop_duplicates(subset=[c for c in df.columns if c != 'ID'], keep='first')
print(f"Rows: {raw_rows} -> {len(df)} after dedup")

df['Income'] = pd.to_numeric(df['Income'], errors='coerce')
missing = df['Income'].isna().sum()
df['Income'] = df['Income'].fillna(df['Income'].median())
print(f"Filled {missing} missing Income values")

df['Marital_Status'] = df['Marital_Status'].replace({'YOLO': 'Single', 'Alone': 'Single', 'Absurd': 'Single'})
df['Dt_Customer'] = pd.to_datetime(df['Dt_Customer'], errors='coerce')

# ---------- 3. FEATURE ENGINEERING ----------
df['Age'] = 2026 - df['Year_Birth']
df['Tenure_Days'] = (df['Dt_Customer'].max() - df['Dt_Customer']).dt.days
df['Total_Children'] = df['Kidhome'] + df['Teenhome']

mnt_cols = [c for c in df.columns if c.startswith('Mnt')]
df['Total_Spend'] = df[mnt_cols].sum(axis=1)
df['Total_Purchases'] = df[['NumWebPurchases','NumCatalogPurchases','NumStorePurchases']].sum(axis=1)

cmp_cols = [c for c in df.columns if c.startswith('AcceptedCmp')]
df['Total_Campaigns_Accepted'] = df[cmp_cols].sum(axis=1) + df['Response']
df['Any_Campaign_Accepted'] = (df['Total_Campaigns_Accepted'] > 0).astype(int)

# ---------- 4. RFM SCORING ----------
df['R_Score'] = pd.qcut(df['Recency'].rank(method='first'), 5, labels=[5,4,3,2,1]).astype(int)
df['F_Score'] = pd.qcut(df['Total_Purchases'].rank(method='first'), 5, labels=[1,2,3,4,5]).astype(int)
df['M_Score'] = pd.qcut(df['Total_Spend'].rank(method='first'), 5, labels=[1,2,3,4,5]).astype(int)
df['RFM_Score'] = df['R_Score'].astype(str) + df['F_Score'].astype(str) + df['M_Score'].astype(str)

# ---------- 5. SEGMENTATION ----------
def segment(row):
    r, f, m = row['R_Score'], row['F_Score'], row['M_Score']
    if r >= 4 and f >= 4 and m >= 4: return 'Champions'
    if r >= 3 and f >= 3 and m >= 3: return 'Loyal Customers'
    if r >= 4 and f <= 2:             return 'New Customers'
    if r <= 2 and f >= 3 and m >= 3:  return 'At Risk'
    if r <= 2 and f <= 2:             return 'Lost'
    return 'Need Attention'

df['Segment'] = df.apply(segment, axis=1)

# ---------- 6. AGGREGATE ----------
summary = (df.groupby('Segment')
             .agg(Customers=('ID', 'count'),
                  Avg_Recency=('Recency', 'mean'),
                  Avg_Spend=('Total_Spend', 'mean'),
                  Total_Revenue=('Total_Spend', 'sum'),
                  Avg_Purchases=('Total_Purchases', 'mean'),
                  Campaign_Acceptance=('Any_Campaign_Accepted', 'mean'),
                  Avg_Income=('Income', 'mean'))
             .round(2)
             .reset_index())

summary['Customer_Share_%'] = (summary['Customers'] / summary['Customers'].sum() * 100).round(1)
summary['Revenue_Share_%'] = (summary['Total_Revenue'] / summary['Total_Revenue'].sum() * 100).round(1)
summary = summary.sort_values('Total_Revenue', ascending=False)

# ---------- 7. INSIGHTS ----------
print("\n" + "="*50)
print("HEADLINE INSIGHTS")
print("="*50)
champ = summary[summary['Segment'] == 'Champions'].iloc[0]
print(f"Champions: {champ['Customer_Share_%']}% of customers -> {champ['Revenue_Share_%']}% of revenue")

ar = summary[summary['Segment'] == 'At Risk']
if not ar.empty:
    a = ar.iloc[0]
    print(f"At Risk: {int(a['Customers'])} customers, ${a['Total_Revenue']:,.0f} revenue at stake")

print(f"Overall campaign acceptance rate: {df['Any_Campaign_Accepted'].mean():.1%}")

# ---------- 8. EXPORT ----------
df.to_csv('customer_segments_clean.csv', index=False)
summary.to_csv('segment_summary.csv', index=False)
print("\nExported: customer_segments_clean.csv + segment_summary.csv")

